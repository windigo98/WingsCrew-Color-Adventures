function sourceInkPng(png, alpha) {
  const out = new PNG({ width: png.width, height: png.height });
  for (let p = 0; p < alpha.length; p++) out.data[p * 4 + 3] = alpha[p];
  return PNG.sync.write(out);
}

export function loadImaginePng(entry) {
  return PNG.sync.read(fs.readFileSync(path.join(root, entry.pack, entry.file)));
}

export function buildImagine(entry) {
  const png = loadImaginePng(entry);
  const traced =
    entry.tier === "adult" ? traceAdult(png, entry) : entry.tier === "big" ? traceMid(png, entry) : tracePage(png, entry);
  traced.display = sourceInkAlpha(png);
  const colors = paintQuill(entry, traced);
  const drawn = vectorizeQuill(entry, traced, colors);
  if (drawn.picture.regions.length !== traced.count) {
    throw new Error(`${entry.id} vectorized ${drawn.picture.regions.length} of ${traced.count}`);
  }
  if (entry.tier === "big" && drawn.picture.regions.length < 60) {
    drawn.picture.note =
      "This drawing closes fewer than 60 cells. Open strokes stay in the ink, and the count is only the regions the lines actually enclose.";
  }
  drawn.picture.inkPng = sourceInkPng(png, traced.display).toString("base64");
  return { traced, colors, ...drawn };
}
