const ADULT_NOTE =
  "Open strokes stay in the original ink. This page counts only the cells those lines actually close.";

function page(def) {
  const base = { rev: 2 };
  if (def.tier === "little") {
    Object.assign(base, {
      thresh: 200,
      seal: 4,
      close: 2,
      pinhole: 36,
      minArea: 2200,
      minRadius: 11,
      maxRegions: 32,
      minRegions: 12,
      keepRadius: 14,
      keepArea: 800,
    });
  } else if (def.tier === "big") {
    Object.assign(base, { thresh: 190, close: 1, minRadius: 2, maxRegions: 200 });
  } else if (def.tier === "adult") {
    Object.assign(base, { thresh: 170, close: 1, minRadius: 2, minCount: 250, shortfall: ADULT_NOTE });
  }
  return { ...base, ...def };
}

